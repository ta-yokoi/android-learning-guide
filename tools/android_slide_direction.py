def enrich(slides):
    assert set(CASES)=={s['chapter'] for s in slides}
    for i,slide in enumerate(slides):
        slide['direction']=CASES[slide['chapter']]
        for m,(name,first,last,accent) in enumerate(MODULES):
            if first<=i<=last:
                slide['module']=dict(name=name,index=m+1,accent=accent)
    return [dict(name=n,first=f,last=l,accent=a) for n,f,l,a in MODULES]
